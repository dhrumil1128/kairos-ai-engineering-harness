"""
File:
core/pipeline/repair_pipeline.py

Purpose:
Execute the
automatic repair
pipeline.

Why:

Separates error
recovery from
generation.

Allows KAIROS to
repair failed code
without coupling
repair logic to the
CLI manager.

Responsibilities:

- Repair generated
  code.
- Save repaired files.
- Return a standard
  pipeline result.

Does NOT:

- Generate projects.
- Validate projects.
- Execute code.

Architecture:

CLI Manager
      │
      ▼
Pipeline Executor
      │
      ▼
Repair Pipeline
      │
      ├── Recursive Engine
      ├── Coder Agent
      ├── Filesystem
      └── Pipeline Result
"""

from __future__ import annotations

import re

from core.logging.kairos_logger import (
    KairosLogger
)

from core.pipeline.pipeline_context import (
    PipelineContext
)

from core.pipeline.pipeline_result import (
    PipelineResult
)
from core.pipeline.path_resolution import (
    resolve_output_path,
)


class RepairPipeline:
    """
    Execute the
    automatic repair
    workflow.
    """

    def __init__(
        self,
        healing,
        coder,
        filesystem
    ):
        """
        Initialize the
        repair pipeline.
        """

        self.logger = (
            KairosLogger(
                "repair_pipeline"
            )
        )

        # Recursive healing
        # engine responsible
        # for recovery plans.
        self.healing = (
            healing
        )

        # AI agent responsible
        # for repairing code.
        self.coder = (
            coder
        )

        # Handles project
        # filesystem
        # operations.
        self.filesystem = (
            filesystem
        )
        
    # ----------------------------------
    # Execute Pipeline
    # ----------------------------------

    def execute(
        self,
        context: PipelineContext,
        implementation: dict,
        error: str,
        retry_count: int
    ) -> PipelineResult:
        """
        Execute the
        repair pipeline.
        """

        self.logger.info(
            "Starting Repair"
        )

        # Analyze the failure
        # and generate a
        # recovery strategy.
        recovery = (
            self.healing.execution_loop.process_error(

                error,

                retry_count

            )
        )

        affected = self._affected_files(
            error,
            implementation
        )

        if not affected:
            self.logger.error(
                "Repair stopped: no affected file identified."
            )

            return PipelineResult.failure_result(
                pipeline="repair",
                data={
                    "error":
                        "Repair requires a specific affected file.",
                    "recovery":
                        recovery,
                    "implementation":
                        implementation,
                }
            )

        scoped_implementation = (
            self._scope_implementation(
                implementation,
                affected
            )
        )

        # Generate repaired
        # implementation.
        repaired = (
            self.coder.repair_code(

                recovery,

                scoped_implementation

            )
        )

        updated_implementation = self._merge_repaired_files(
            implementation,
            repaired
        )

        # Save only affected
        # repaired files.
        for file in repaired[
            "implementation_spec"
        ][
            "files"
        ]:

            self.filesystem.execute(

                "write",

                resolve_output_path(
                    context.generated_project,
                    file["path"],
                ),

                file["content"]

            )

        self.logger.success(
            "Repair completed"
        )

        # Return a standardized
        # pipeline result so the
        # Pipeline Executor can
        # process every pipeline
        # identically.
        return PipelineResult.success_result(

            pipeline="repair",

            data={

                # Recovery strategy
                # generated by the
                # Healing Engine.
                "recovery":
                    recovery,

                # Final repaired
                # implementation.
                "implementation":
                    updated_implementation,

            }

        )

    def _affected_files(
        self,
        error: str,
        implementation: dict,
    ) -> set[str]:
        files = {
            file.get("path")
            for file in implementation.get(
                "implementation_spec",
                {}
            ).get(
                "files",
                []
            )
            if file.get("path")
        }
        affected = set()
        candidates = re.findall(
            r'File "([^"]+)"|([A-Za-z]:\\[^\s\'"]+|[\w./\\-]+\.(?:py|js|java|cpp|cc|json|txt|md))',
            str(error),
        )

        for first, second in candidates:
            candidate = (
                first
                or second
            ).replace(
                "\\",
                "/"
            )

            for file_path in files:
                normalized = file_path.replace(
                    "\\",
                    "/"
                )

                if (
                    candidate.endswith(normalized)
                    or normalized.endswith(candidate)
                ):
                    affected.add(file_path)

        return affected

    def _scope_implementation(
        self,
        implementation: dict,
        affected: set[str],
    ) -> dict:
        scoped = dict(
            implementation
        )
        scoped["implementation_spec"] = {
            "files": [
                file
                for file in implementation.get(
                    "implementation_spec",
                    {}
                ).get(
                    "files",
                    []
                )
                if file.get("path") in affected
            ]
        }

        return scoped

    def _merge_repaired_files(
        self,
        implementation: dict,
        repaired: dict,
    ) -> dict:
        repaired_by_path = {
            file["path"]: file
            for file in repaired.get(
                "implementation_spec",
                {}
            ).get(
                "files",
                []
            )
            if file.get("path")
        }
        merged = dict(
            implementation
        )
        merged["implementation_spec"] = {
            "files": [
                repaired_by_path.get(
                    file.get("path"),
                    file
                )
                for file in implementation.get(
                    "implementation_spec",
                    {}
                ).get(
                    "files",
                    []
                )
            ]
        }

        return merged
    
    # ----------------------------------
    # Pipeline Name
    # ----------------------------------

    @property  # Read-only property. Access like obj.name instead of obj.name().
    def name(
        self
    ) -> str:
        """
        Return the
        pipeline name.
        """

        return "repair"
    
    
    # ----------------------------------
    # Supports Pipeline
    # ----------------------------------

    def supports(
        self,
        pipeline: str
    ) -> bool:
        """
        Check whether this
        pipeline can execute
        the requested task.
        """

        return (
            pipeline ==
            self.name
        )
        
    
    # ----------------------------------
    # List Supported Pipelines
    # ----------------------------------

    @classmethod  # Can be called without creating a RepairPipeline object.
    def supported_pipelines(
        cls
    ) -> list[str]:
        """
        Return every
        pipeline supported
        by this class.
        """

        return [

            "repair"

        ]
